export const PCNLookup = (): React.ReactElement => {
  const location = useLocation();
  // Extract locale from pathname (e.g., /fr/tools or /de/tools or /tools)
  const pathLocale = location.pathname.split('/')[1];
  const locale = pathLocale === 'fr' || pathLocale === 'de' ? pathLocale : 'en';
  const [searchTerm, setSearchTerm] = useState('');
  const [selectedClass, setSelectedClass] = useState('all');

  const getAccountName = (account: PcnAccount): string => {
    if (locale === 'fr') return account.nameFr;
    if (locale === 'de') return account.nameDe;
    return account.nameEn;
  };

  const getAccountClass = (account: PcnAccount): string => {
    if (locale === 'fr') return account.classFr;
    if (locale === 'de') return account.classDe;
    return account.classEn;
  };

  const getAccountDescription = (account: PcnAccount): string => {
    if (locale === 'fr') return account.descriptionFr;
    if (locale === 'de') return account.descriptionDe;
    return account.descriptionEn;
  };

  const filteredAccounts = useMemo(() => {
    const query = searchTerm.trim().toLowerCase();
    return SAMPLE_PCN_ACCOUNTS.filter((account) => {
      const name = getAccountName(account).toLowerCase();
      const description = getAccountDescription(account).toLowerCase();
      const matchesQuery =
        !query ||
        account.code.includes(query) ||
        name.includes(query) ||
        description.includes(query);
      const accountClass = getAccountClass(account);
      const matchesClass = selectedClass === 'all' || accountClass === selectedClass;
      return matchesQuery && matchesClass;
    });
  }, [searchTerm, selectedClass, locale]);

  const uniqueClasses = useMemo(() => {
    return Array.from(new Set(SAMPLE_PCN_ACCOUNTS.map((account) => getAccountClass(account))));
  }, [locale]);

  return (
    <section className={styles.toolCard} id="pcn-lookup">
      <h2>
        <Translate id="pcn.title">PCN 2020 Lookup</Translate>
      </h2>
      <p className="text--secondary">
        <Translate id="pcn.description">Quickly search Luxembourg PCN accounts for journal entries, teaching, or SME coaching.</Translate>
      </p>

      <div className={styles.inlineFields}>
        <label>
          <span className="text--bold">
            <Translate id="pcn.searchLabel">Search code or keyword</Translate>
          </span>
          <input
            type="text"
            value={searchTerm}
            onChange={(e) => setSearchTerm(e.target.value)}
            className="margin-top--xs"
            placeholder={translate({id: 'pcn.searchPlaceholder', message: 'e.g., TVA, 461411, salaires'})}
          />
        </label>
        <label>
          <span className="text--bold">
            <Translate id="pcn.classLabel">PCN Class</Translate>
          </span>
          <select value={selectedClass} onChange={(e) => setSelectedClass(e.target.value)} className="margin-top--xs">
            <option value="all">
              {translate({id: 'pcn.allClasses', message: 'All classes'})}
            </option>
            {uniqueClasses.map((pcnClass) => (
              <option key={pcnClass} value={pcnClass}>
                {pcnClass}
              </option>
            ))}
          </select>
        </label>
      </div>

      <table className={styles.table}>
        <thead>
          <tr>
            <th>
              <Translate id="pcn.tableCode">Code</Translate>
            </th>
            <th>
              <Translate id="pcn.tableAccount">Account</Translate>
            </th>
            <th>
              <Translate id="pcn.tableClass">Class</Translate>
            </th>
            <th>
              <Translate id="pcn.tableDescription">Description</Translate>
            </th>
          </tr>
        </thead>
        <tbody>
          {filteredAccounts.length === 0 ? (
            <tr>
              <td colSpan={4} className="text--center text--secondary">
                <Translate id="pcn.noAccounts">No accounts match your criteria.</Translate>
              </td>
            </tr>
          ) : (
            filteredAccounts.map((account) => (
              <tr key={account.code}>
                <td>{account.code}</td>
                <td>{getAccountName(account)}</td>
                <td>{getAccountClass(account)}</td>
                <td>{getAccountDescription(account)}</td>
              </tr>
            ))
          )}
        </tbody>
      </table>
      <p className="margin-top--sm text--small text--secondary">
        <Translate id="pcn.note">
          Selected accounts of the official PCN 2020. See Appendix A for how the numbering works; the full chart is in the
          Règlement grand-ducal of 12 September 2019.
        </Translate>
      </p>
    </section>
  );
};

